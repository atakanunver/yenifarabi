# Komşuluk vektörleri (Axial coordinates: dq, dr)
KOMSU_YONLER = [(1, 0), (1, -1), (0, -1), (-1, 0), (-1, 1), (0, 1)]


def komsulari_hesapla() -> dict[int, list[int]]:
    """19 peteğin her birinin doğrudan temas ettiği komşu petek ID'lerini üretir."""
    koordinat_haritasi = {(p["q"], p["r"]): p["id"] for p in HEX_TOPOLOJI}
    komsuluk: dict[int, list[int]] = {}

    for p in HEX_TOPOLOJI:
        pid = p["id"]
        q, r = p["q"], p["r"]
        komsular = []
        for dq, dr in KOMSU_YONLER:
            hedef = (q + dq, r + dr)
            if hedef in koordinat_haritasi:
                komsular.append(koordinat_haritasi[hedef])
        komsuluk[pid] = komsular
    return komsuluk


KOMSULUK = komsulari_hesapla()


def piksel_koordinatlari(center_x: float = 480.0, center_y: float = 380.0, size: float = 68.0) -> list[dict[str, Any]]:
    """Pointy-topped hexagonlar için SVG (cx, cy) ekran koordinatlarını ve köşe noktalarını üretir."""
    harita = []
    for p in HEX_TOPOLOJI:
        q, r = p["q"], p["r"]
        cx = center_x + size * math.sqrt(3) * (q + r / 2.0)
        cy = center_y + size * (3.0 / 2.0) * r

        noktalar = []
        for i in range(6):
            aci_deg = 60 * i - 30
            aci_rad = math.pi / 180.0 * aci_deg
            px = cx + size * math.cos(aci_rad)
            py = cy + size * math.sin(aci_rad)
            noktalar.append(f"{px:.1f},{py:.1f}")

        harita.append({
            **p,
            "cx": round(cx, 1),
            "cy": round(cy, 1),
            "points": " ".join(noktalar),
            "komsular": KOMSULUK[p["id"]],
        })
    return harita


