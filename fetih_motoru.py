def normalize_ders_adi(s: str) -> str:
    if not s:
        return ""
    return s.replace("İ", "i").replace("I", "ı").lower().strip()


def haritayi_hazirla(ders_adi: str, sinif: int = 9) -> list[dict[str, Any]]:
    """Belirtilen ders için 19 peteklik harita düğümlerini sorularıyla birleştirir.
    Soru havuzunda (AGY onaylı) o ders+sınıf için yeterli soru varsa her petek farklı
    bir havuz sorusu alır; yoksa statik soru listesi kullanılır."""
    ders_temiz = normalize_ders_adi(ders_adi)
    ders_key = "biyoloji"

    # 1. Kapsam eşleme tablosundan ara
    for k, v in soru_uretici.KAPSAM_ESLEME.items():
        k_norm = normalize_ders_adi(k)
        if k_norm in ders_temiz or ders_temiz in k_norm:
            ders_key = v
            break

    # 2. Soru listesini al
    soru_listesi = DERS_KONULARI_VE_SORULAR.get(ders_key)
    if not soru_listesi:
        # Doğrudan ders_temiz olarak dene
        soru_listesi = DERS_KONULARI_VE_SORULAR.get(ders_temiz, DERS_KONULARI_VE_SORULAR["biyoloji"])

    grid = piksel_koordinatlari()
    havuzdan = havuz.petek_sorulari(ders_key, sinif, len(grid))
    if havuzdan:
        soru_listesi = havuzdan
    dugumler = []

    for i, geo in enumerate(grid):
        soru_bilgi = soru_listesi[i % len(soru_listesi)]
        dugumler.append({
            "id": geo["id"],
            "q": geo["q"],
            "r": geo["r"],
            "cx": geo["cx"],
            "cy": geo["cy"],
            "points": geo["points"],
            "komsular": geo["komsular"],
            "seviye": geo["seviye"],
            "puan": geo["puan"],
            "tip": geo["tip"],
            "konu": soru_bilgi["konu"],
            "soru": {
                "soru_metni": soru_bilgi["q"],
                "secenekler": soru_bilgi["secenekler"],
                "dogru_cevap": soru_bilgi["a"],
                "kaynak": soru_bilgi["kaynak"] if str(soru_bilgi["kaynak"]).startswith("MEB ") else f"MEB {soru_bilgi['kaynak']}",
            },
            "sahip": None,

            "kalkan": False,
        })

    return dugumler


def baglantili_kombo_hesapla(dugumler: list[dict[str, Any]], takim_index: int) -> int:
    """Belirtilen takımın birbiriyle temas eden en uzun kesintisiz petek zincirini hesaplar (BFS)."""
    takim_dugumlari = {d["id"] for d in dugumler if d.get("sahip") == takim_index}
    if not takim_dugumlari:
        return 0

    komsuluk_sozlugu = {d["id"]: set(d["komsular"]) for d in dugumler}
    ziyaret_edilen = set()
    en_buyuk_kume = 0

    for baslangic in takim_dugumlari:
        if baslangic in ziyaret_edilen:
            continue
        kume_boyutu = 0
        kuyruk = [baslangic]
        ziyaret_edilen.add(baslangic)

        while kuyruk:
            mevcut = kuyruk.pop(0)
            kume_boyutu += 1
            for komsu in komsuluk_sozlugu.get(mevcut, set()):
                if komsu in takim_dugumlari and komsu not in ziyaret_edilen:
                    ziyaret_edilen.add(komsu)
                    kuyruk.append(komsu)

        if kume_boyutu > en_buyuk_kume:
            en_buyuk_kume = kume_boyutu

    return en_buyuk_kume
