"""okul_dosya_yukle.py — Excel (xls/xlsx) sayfalarını ve Word (docx) tablolarını okul_ana.dosya / dosya_satir tablolarına yükler.

Atos bu tablolara SQL ile ulaşır (okul_sql.PG_TABLOLARI). Dosyalar bir klasöre kopyalanmış olmalı; kök klasör altındaki
göreli yol `dosya.yol` olur. xlrd + openpyxl + psycopg gerekir (canlı venv'lerde yok → osym/venv kullanılır):

    osym/venv/bin/python tahtayoklama/dashboard/scripts/okul_dosya_yukle.py <kök> [--gun 31] [--kuru]

Yalnızca son --gun günde değişen dosyalar alınır. Aynı yol + aynı içerik (sha256) yeniden yüklenmez; içerik değişmişse
dosyanın satırları silinip yeniden yazılır. Word'de yalnızca TABLOLAR alınır (paragraf metni değil).
Bağlantı: ~/.config/okul-ana/baglanti (okul_ana rolü). Tablolar sema_sql ile postgres tarafından kurulur.
"""

from __future__ import annotations

import argparse
import collections
import datetime
import hashlib
import json
import sys
import time
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

SEMA_SQL = """
CREATE TABLE IF NOT EXISTS okul_ana.dosya (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    yol          text NOT NULL UNIQUE,      -- kök klasöre göre göreli yol
    klasor       text NOT NULL,             -- yolun klasör kısmı
    ad           text NOT NULL,
    tur          text NOT NULL,             -- xlsx | xls | docx
    sayfa_sayisi integer NOT NULL,
    satir_sayisi integer NOT NULL,
    dosya_zamani timestamptz,
    yuklenme     timestamptz NOT NULL DEFAULT now(),
    sha256       text NOT NULL
);
CREATE TABLE IF NOT EXISTS okul_ana.dosya_satir (
    dosya_id integer NOT NULL REFERENCES okul_ana.dosya(id) ON DELETE CASCADE,
    sayfa    text    NOT NULL,              -- Excel sayfa adı / Word'de "tablo N"
    satir_no integer NOT NULL,              -- sayfadaki sıra (1'den)
    hucreler jsonb   NOT NULL,              -- hücreler sırayla (metin dizisi)
    metin    text    NOT NULL               -- boş olmayan hücreler " | " ile (LIKE araması için)
);
CREATE INDEX IF NOT EXISTS dosya_satir_dosya ON okul_ana.dosya_satir (dosya_id);
GRANT SELECT, INSERT, UPDATE, DELETE ON okul_ana.dosya, okul_ana.dosya_satir TO okul_ana;
GRANT SELECT ON okul_ana.dosya, okul_ana.dosya_satir TO atos_ro;
"""
AZAMI_HUCRE = 2000
_W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def hucre(v) -> str:
    if v is None:
        return ""
    if isinstance(v, bool):
        return "evet" if v else "hayır"
    if isinstance(v, datetime.datetime):
        return v.date().isoformat() if v.time() == datetime.time(0) else v.isoformat(sep=" ")
    if isinstance(v, datetime.date):
        return v.isoformat()
    if isinstance(v, float):
        return str(int(v)) if v.is_integer() else format(v, ".10g")
    return " ".join(str(v).split())[:AZAMI_HUCRE]


def satirlari_temizle(satirlar):
    """(sayfa, [hücre,...]) akışından boş satırları atar, sondaki boş hücreleri keser, satır numarası verir."""
    sayac: dict[str, int] = collections.defaultdict(int)
    for sayfa, hucreler in satirlar:
        h = [hucre(x) for x in hucreler]
        while h and not h[-1]:
            h.pop()
        if not h:
            continue
        sayac[sayfa] += 1
        yield sayfa, sayac[sayfa], h


def xlsx_satirlari(yol):
    import openpyxl

    wb = openpyxl.load_workbook(yol, read_only=True, data_only=True)
    for ws in wb.worksheets:
        for satir in ws.iter_rows(values_only=True):
            yield ws.title, satir


def xls_satirlari(yol):
    import xlrd

    with open("/dev/null", "w") as log:
        wb = xlrd.open_workbook(str(yol), logfile=log)
    for sh in wb.sheets():
        for r in range(sh.nrows):
            satir = []
            for c in range(sh.ncols):
                tip, v = sh.cell_type(r, c), sh.cell_value(r, c)
                if tip == xlrd.XL_CELL_DATE:
                    try:
                        v = xlrd.xldate.xldate_as_datetime(v, wb.datemode)
                    except (ValueError, xlrd.xldate.XLDateError):
                        v = str(v)  # bozuk tarih seri sayısı ham kalsın
                satir.append(v)
            yield sh.name, satir


def docx_satirlari(yol):
    with zipfile.ZipFile(yol) as z:
        govde = ET.fromstring(z.read("word/document.xml")).find(f"{_W}body")
    for n, tbl in enumerate(govde.iter(f"{_W}tbl"), 1):
        for tr in tbl.findall(f"{_W}tr"):
            yield f"tablo {n}", ["".join(t.text or "" for t in tc.iter(f"{_W}t")) for tc in tr.findall(f"{_W}tc")]


OKUYUCU = {".xlsx": xlsx_satirlari, ".xls": xls_satirlari, ".docx": docx_satirlari}


def dosyalari_bul(kok: Path, gun: int):
    sinir = time.time() - gun * 86400
    for yol in sorted(kok.rglob("*")):
        if yol.is_file() and yol.suffix.lower() in OKUYUCU and not yol.name.startswith("~$") and yol.stat().st_mtime >= sinir:
            yield yol


def yukle(c, kok: Path, yol: Path, kuru: bool) -> str:
    goreli = yol.relative_to(kok).as_posix()
    sha = hashlib.sha256(yol.read_bytes()).hexdigest()
    mevcut = c.execute("SELECT id, sha256 FROM okul_ana.dosya WHERE yol=%s", (goreli,)).fetchone()
    if mevcut and mevcut[1] == sha:
        return "değişmemiş"
    satirlar = list(satirlari_temizle(OKUYUCU[yol.suffix.lower()](yol)))
    sayfalar = {s for s, _, _ in satirlar}
    if kuru:
        return f"{len(satirlar)} satır, {len(sayfalar)} sayfa (kuru)"
    if mevcut:
        c.execute("DELETE FROM okul_ana.dosya WHERE id=%s", (mevcut[0],))
    zaman = datetime.datetime.fromtimestamp(yol.stat().st_mtime, datetime.timezone.utc)
    did = c.execute(
        "INSERT INTO okul_ana.dosya (yol, klasor, ad, tur, sayfa_sayisi, satir_sayisi, dosya_zamani, sha256) "
        "VALUES (%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id",
        (goreli, str(Path(goreli).parent), yol.name, yol.suffix.lower().lstrip("."), len(sayfalar), len(satirlar), zaman, sha),
    ).fetchone()[0]
    with c.cursor() as cur:
        cur.executemany(
            "INSERT INTO okul_ana.dosya_satir (dosya_id, sayfa, satir_no, hucreler, metin) VALUES (%s,%s,%s,%s::jsonb,%s)",
            [(did, s, n, json.dumps(h, ensure_ascii=False), " | ".join(x for x in h if x)) for s, n, h in satirlar],
        )
    return f"{len(satirlar)} satır, {len(sayfalar)} sayfa"


def main(argv=None) -> int:
    import psycopg

    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("kok")
    p.add_argument("--gun", type=int, default=31)
    p.add_argument("--kuru", action="store_true")
    a = p.parse_args(argv)
    kok = Path(a.kok).resolve()
    dsn = (Path.home() / ".config/okul-ana/baglanti").read_text(encoding="utf-8").strip()
    toplam, hata = collections.Counter(), 0
    with psycopg.connect(dsn) as c:
        for yol in dosyalari_bul(kok, a.gun):
            try:
                sonuc = yukle(c, kok, yol, a.kuru)
                toplam[sonuc.split()[0] if sonuc[0].isdigit() else sonuc] += 1
            except Exception as e:  # noqa: BLE001 — bozuk dosya diğerlerini durdurmasın
                sonuc, hata = f"HATA {type(e).__name__}: {str(e)[:80]}", hata + 1
            print(f"{yol.relative_to(kok).as_posix()[:78]:78} {sonuc}")
        if a.kuru:
            c.rollback()
    print(f"\nözet: {sum(toplam.values()) - hata} dosya işlendi, {hata} hata")
    return 1 if hata else 0


if __name__ == "__main__":
    sys.exit(main())
